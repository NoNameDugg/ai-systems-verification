/// Reason for order cancellation.
///
/// Provides context for why an order was cancelled.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum CancelReason {
    /// User requested cancellation.
    UserRequested,
    /// Order expired (GTD).
    Expired,
    /// Insufficient funds/margin.
    InsufficientFunds,
    /// Post-only order would take liquidity.
    PostOnlyWouldTake,
    /// Reduce-only order would increase position.
    ReduceOnlyWouldIncrease,
    /// Self-trade prevention triggered.
    SelfTradePrevention,
    /// Order cancelled due to disconnect.
    Disconnect,
    /// System shutdown/maintenance.
    SystemShutdown,
    /// Risk limit exceeded.
    RiskLimit,
    /// Custom reason with message.
    Other(String),
}

impl CancelReason {
    /// Returns the string representation.
    pub fn as_str(&self) -> &str {
        match self {
            Self::UserRequested => "user_requested",
            Self::Expired => "expired",
            Self::InsufficientFunds => "insufficient_funds",
            Self::PostOnlyWouldTake => "post_only_would_take",
            Self::ReduceOnlyWouldIncrease => "reduce_only_would_increase",
            Self::SelfTradePrevention => "self_trade_prevention",
            Self::Disconnect => "disconnect",
            Self::SystemShutdown => "system_shutdown",
            Self::RiskLimit => "risk_limit",
            Self::Other(msg) => msg,
        }
    }
}

impl fmt::Display for CancelReason {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.as_str())
    }
}

