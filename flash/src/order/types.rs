/// Order lifecycle status.
///
/// Tracks the current state of an order from submission to completion.
///
/// # State Machine
///
/// ```text
/// Pending ──submit──> Submitted ──ack──> Open ──fill──> Filled
///                          │                │               │
///                          │              cancel           partial
///                          │                │               │
///                          └──reject──> Rejected      PartiallyFilled
///                                                           │
///                                                       cancel
///                                                           │
///                                                       Cancelled
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum OrderStatus {
    /// Order created but not yet sent to exchange.
    Pending,
    /// Order sent to exchange, awaiting acknowledgment.
    Submitted,
    /// Order acknowledged by exchange and active.
    Open,
    /// Order partially filled.
    PartiallyFilled,
    /// Order completely filled.
    Filled,
    /// Order cancelled (by user or system).
    Cancelled,
    /// Order rejected by exchange.
    Rejected,
    /// Order expired (GTD orders).
    Expired,
}

impl OrderStatus {
    /// Returns the string representation.
    #[must_use]
    pub const fn as_str(&self) -> &'static str {
        match self {
            Self::Pending => "pending",
            Self::Submitted => "submitted",
            Self::Open => "open",
            Self::PartiallyFilled => "partially_filled",
            Self::Filled => "filled",
            Self::Cancelled => "cancelled",
            Self::Rejected => "rejected",
            Self::Expired => "expired",
        }
    }

    /// Returns true if the order is in a terminal state.
    #[must_use]
    pub const fn is_terminal(&self) -> bool {
        matches!(
            self,
            Self::Filled | Self::Cancelled | Self::Rejected | Self::Expired
        )
    }

    /// Returns true if the order can be cancelled.
    #[must_use]
    pub const fn is_cancellable(&self) -> bool {
        matches!(self, Self::Open | Self::PartiallyFilled | Self::Submitted)
    }
}

impl fmt::Display for OrderStatus {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.as_str())
    }
}

