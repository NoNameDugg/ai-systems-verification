//! Order type definitions for Flash.
//!
//! This module defines the core order types used throughout the order management
//! system. All types are designed for:
//!
//! - **Zero-Copy Serialization**: Efficient bincode encoding for BlackBox
//! - **Serde Compatible**: JSON serialization for debugging/logging
//! - **Thread-Safe**: All types are `Send + Sync`
//!
//! # Types Overview
//!
//! | Type | Description | Size |
//! |------|-------------|------|
//! | `OrderId` | Unique order identifier | 8 bytes |
//! | `OrderType` | Market/Limit/StopLimit | 1 byte |
//! | `OrderSide` | Buy/Sell | 1 byte |
//! | `TimeInForce` | GTC/IOC/FOK | 1 byte |
//! | `OrderRequest` | Full order submission | ~128 bytes |

use crate::core::types::{Instrument, Quantity, Timestamp};
use serde::{Deserialize, Serialize};
use std::fmt;

// =============================================================================
// ORDER ID
// =============================================================================

/// Unique order identifier.
///
/// A 64-bit unsigned integer that uniquely identifies an order within the system.
/// Order IDs are generated by the [`OrderManager`] and are monotonically increasing.
///
/// # Example
///
/// ```
/// use astra_flash::order::OrderId;
///
/// let id = OrderId::new(12345);
/// assert_eq!(id.as_u64(), 12345);
/// assert_eq!(id.to_string(), "12345");
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct OrderId(u64);

impl OrderId {
    /// Creates a new order ID from a u64 value.
    #[must_use]
    pub const fn new(id: u64) -> Self {
        Self(id)
    }

    /// Returns the underlying u64 value.
    #[must_use]
    pub const fn as_u64(&self) -> u64 {
        self.0
    }
}

impl fmt::Display for OrderId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl From<u64> for OrderId {
    fn from(value: u64) -> Self {
        Self::new(value)
    }
}

