/// Time-in-force specification.
///
/// Defines how long an order remains active before being cancelled.
///
/// # Example
///
/// ```
/// use astra_flash::order::TimeInForce;
///
/// let tif = TimeInForce::GTC;
/// assert_eq!(tif.as_str(), "GTC");
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
pub enum TimeInForce {
    /// Good-Till-Cancelled - remains active until filled or cancelled.
    #[default]
    GTC,
    /// Immediate-Or-Cancel - fill what can be filled, cancel the rest.
    IOC,
    /// Fill-Or-Kill - fill completely or cancel entirely.
    FOK,
    /// Good-Till-Date - expires at specified time.
    GTD,
    /// Post-Only - only add liquidity, never take.
    PostOnly,
}

impl TimeInForce {
    /// Returns the string representation.
    #[must_use]
    pub const fn as_str(&self) -> &'static str {
        match self {
            Self::GTC => "GTC",
            Self::IOC => "IOC",
            Self::FOK => "FOK",
            Self::GTD => "GTD",
            Self::PostOnly => "POST_ONLY",
        }
    }
}

impl fmt::Display for TimeInForce {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.as_str())
    }
}

