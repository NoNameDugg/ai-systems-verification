/// Order type classification.
///
/// Defines how the order should be executed by the exchange.
///
/// # Example
///
/// ```
/// use astra_flash::order::OrderType;
///
/// let order_type = OrderType::Limit;
/// assert_eq!(order_type.as_str(), "limit");
/// assert!(order_type.requires_price());  // Limit orders require a price
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum OrderType {
    /// Market order - execute at best available price.
    Market,
    /// Limit order - execute at specified price or better.
    Limit,
    /// Stop limit order - becomes limit order when stop price is reached.
    StopLimit,
    /// Stop market order - becomes market order when stop price is reached.
    StopMarket,
}

impl OrderType {
    /// Returns the string representation.
    #[must_use]
    pub const fn as_str(&self) -> &'static str {
        match self {
            Self::Market => "market",
            Self::Limit => "limit",
            Self::StopLimit => "stop_limit",
            Self::StopMarket => "stop_market",
        }
    }

    /// Returns true if this order type requires a price.
    #[must_use]
    pub const fn requires_price(&self) -> bool {
        match self {
            Self::Market | Self::StopMarket => false,
            Self::Limit | Self::StopLimit => true,
        }
    }

    /// Returns true if this order type requires a stop price.
    #[must_use]
    pub const fn requires_stop_price(&self) -> bool {
        matches!(self, Self::StopLimit | Self::StopMarket)
    }
}

impl fmt::Display for OrderType {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.as_str())
    }
}

