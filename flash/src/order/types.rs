/// Order modification request.
///
/// Contains the changes to apply to an existing order.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ModifyRequest {
    /// New price (if changing).
    /// Stored as f64 for serialization compatibility.
    pub new_price: Option<f64>,

    /// New quantity (if changing).
    pub new_quantity: Option<Quantity>,

    /// Timestamp of modification request.
    pub timestamp: Timestamp,
}

impl ModifyRequest {
    /// Creates a new modification request to change the price.
    #[must_use]
    pub const fn price(new_price: f64, timestamp: Timestamp) -> Self {
        Self {
            new_price: Some(new_price),
            new_quantity: None,
            timestamp,
        }
    }

    /// Creates a new modification request to change the quantity.
    #[must_use]
    pub const fn quantity(new_quantity: Quantity, timestamp: Timestamp) -> Self {
        Self {
            new_price: None,
            new_quantity: Some(new_quantity),
            timestamp,
        }
    }

    /// Creates a new modification request to change both price and quantity.
    #[must_use]
    pub const fn price_and_quantity(
        new_price: f64,
        new_quantity: Quantity,
        timestamp: Timestamp,
    ) -> Self {
        Self {
            new_price: Some(new_price),
            new_quantity: Some(new_quantity),
            timestamp,
        }
    }
}

