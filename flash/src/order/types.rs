/// Order submission request.
///
/// Contains all information needed to submit an order to an exchange.
/// This struct is serialized and recorded to the BlackBox journal when
/// the `blackbox` feature is enabled.
///
/// # Example
///
/// ```
/// use astra_flash::order::{OrderRequest, OrderType, OrderSide, TimeInForce};
/// use astra_flash::core::types::{Exchange, Instrument, now_micros};
/// use rust_decimal_macros::dec;
///
/// let instrument = Instrument::new("BTC", "USD", Exchange::Deribit, "BTC-PERPETUAL");
/// let order = OrderRequest::limit(
///     instrument,
///     OrderSide::Buy,
///     50000.0,
///     dec!(1.0),
///     TimeInForce::GTC,
///     now_micros(),
/// );
///
/// assert_eq!(order.order_type, OrderType::Limit);
/// assert_eq!(order.side, OrderSide::Buy);
/// ```
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct OrderRequest {
    /// Instrument to trade.
    pub instrument: Instrument,

    /// Order side (buy/sell).
    pub side: OrderSide,

    /// Order type (market/limit/stop).
    pub order_type: OrderType,

    /// Order quantity.
    pub quantity: Quantity,

    /// Limit price (required for Limit and StopLimit orders).
    /// Stored as f64 for serialization compatibility.
    pub price: Option<f64>,

    /// Stop trigger price (required for Stop orders).
    /// Stored as f64 for serialization compatibility.
    pub stop_price: Option<f64>,

    /// Time in force.
    pub time_in_force: TimeInForce,

    /// Client-defined order ID (optional).
    pub client_order_id: Option<String>,

    /// Reduce-only flag (close positions only).
    pub reduce_only: bool,

    /// Post-only flag (add liquidity only).
    pub post_only: bool,

    /// Creation timestamp (microseconds).
    pub created_at: Timestamp,
}

impl OrderRequest {
    /// Creates a new market order request.
    ///
    /// Market orders execute immediately at the best available price.
    ///
    /// # Arguments
    ///
    /// * `instrument` - Trading instrument
    /// * `side` - Buy or sell
    /// * `quantity` - Order quantity
    /// * `timestamp` - Creation timestamp
    ///
    /// # Example
    ///
    /// ```
    /// use astra_flash::order::{OrderRequest, OrderSide};
    /// use astra_flash::core::types::{Exchange, Instrument, now_micros};
    /// use rust_decimal_macros::dec;
    ///
    /// let instrument = Instrument::new("BTC", "USD", Exchange::Deribit, "BTC-PERPETUAL");
    /// let order = OrderRequest::market(instrument, OrderSide::Buy, dec!(1.0), now_micros());
    /// ```
    #[must_use]
    pub const fn market(
        instrument: Instrument,
        side: OrderSide,
        quantity: Quantity,
        timestamp: Timestamp,
    ) -> Self {
        Self {
            instrument,
            side,
            order_type: OrderType::Market,
            quantity,
            price: None,
            stop_price: None,
            time_in_force: TimeInForce::IOC,
            client_order_id: None,
            reduce_only: false,
            post_only: false,
            created_at: timestamp,
        }
    }

    /// Creates a new limit order request.
    ///
    /// Limit orders execute at the specified price or better.
    ///
    /// # Arguments
    ///
    /// * `instrument` - Trading instrument
    /// * `side` - Buy or sell
    /// * `price` - Limit price
    /// * `quantity` - Order quantity
    /// * `time_in_force` - How long the order remains active
    /// * `timestamp` - Creation timestamp
    ///
    /// # Example
    ///
    /// ```
    /// use astra_flash::order::{OrderRequest, OrderSide, TimeInForce};
    /// use astra_flash::core::types::{Exchange, Instrument, now_micros};
    /// use rust_decimal_macros::dec;
    ///
    /// let instrument = Instrument::new("BTC", "USD", Exchange::Deribit, "BTC-PERPETUAL");
    /// let order = OrderRequest::limit(
    ///     instrument,
    ///     OrderSide::Buy,
    ///     50000.0,
    ///     dec!(1.0),
    ///     TimeInForce::GTC,
    ///     now_micros(),
    /// );
    /// ```
    #[must_use]
    pub const fn limit(
        instrument: Instrument,
        side: OrderSide,
        price: f64,
        quantity: Quantity,
        time_in_force: TimeInForce,
        timestamp: Timestamp,
    ) -> Self {
        Self {
            instrument,
            side,
            order_type: OrderType::Limit,
            quantity,
            price: Some(price),
            stop_price: None,
            time_in_force,
            client_order_id: None,
            reduce_only: false,
            post_only: false,
            created_at: timestamp,
        }
    }

    /// Creates a new stop-limit order request.
    ///
    /// Stop-limit orders become limit orders when the stop price is reached.
    ///
    /// # Arguments
    ///
    /// * `instrument` - Trading instrument
    /// * `side` - Buy or sell
    /// * `stop_price` - Trigger price
    /// * `limit_price` - Limit price after trigger
    /// * `quantity` - Order quantity
    /// * `timestamp` - Creation timestamp
    #[must_use]
    pub const fn stop_limit(
        instrument: Instrument,
        side: OrderSide,
        stop_price: f64,
        limit_price: f64,
        quantity: Quantity,
        timestamp: Timestamp,
    ) -> Self {
        Self {
            instrument,
            side,
            order_type: OrderType::StopLimit,
            quantity,
            price: Some(limit_price),
            stop_price: Some(stop_price),
            time_in_force: TimeInForce::GTC,
            client_order_id: None,
            reduce_only: false,
            post_only: false,
            created_at: timestamp,
        }
    }

    /// Sets the client order ID.
    #[must_use]
    pub fn with_client_id(mut self, client_id: impl Into<String>) -> Self {
        self.client_order_id = Some(client_id.into());
        self
    }

    /// Sets the reduce-only flag.
    #[must_use]
    pub const fn reduce_only(mut self) -> Self {
        self.reduce_only = true;
        self
    }

    /// Sets the post-only flag.
    #[must_use]
    pub const fn post_only(mut self) -> Self {
        self.post_only = true;
        self
    }
}

