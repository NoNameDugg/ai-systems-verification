/// Order side (buy or sell).
///
/// Distinct from [`Side`](crate::core::types::Side) which represents book side.
/// This enum represents the trading intent.
///
/// # Example
///
/// ```
/// use astra_flash::order::OrderSide;
///
/// let side = OrderSide::Buy;
/// assert_eq!(side.as_str(), "buy");
/// assert_eq!(side.opposite(), OrderSide::Sell);
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum OrderSide {
    /// Buy order (bid).
    Buy,
    /// Sell order (ask).
    Sell,
}

impl OrderSide {
    /// Returns the opposite side.
    #[must_use]
    pub const fn opposite(&self) -> Self {
        match self {
            Self::Buy => Self::Sell,
            Self::Sell => Self::Buy,
        }
    }

    /// Returns the string representation.
    #[must_use]
    pub const fn as_str(&self) -> &'static str {
        match self {
            Self::Buy => "buy",
            Self::Sell => "sell",
        }
    }
}

impl fmt::Display for OrderSide {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.as_str())
    }
}

